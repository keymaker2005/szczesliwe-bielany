// tools/guide-texts.mjs
// Builds js/guide-texts.js from the JSON block at the top of docs/teksty-przewodnika.md: the guide's texts keyed to
// the landmark sites of js/guide.js, and the mayor's draft messages with what triggers them. --public leaves the
// mayor's messages out (they wait for his or the district office's approval): tools/build-dist.mjs uses it.
//
// usage: node tools/guide-texts.mjs [outFile] [--public]

import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const PUBLIC = args.includes('--public');
const OUT = args.find((a) => !a.startsWith('--')) || ROOT + 'js/guide-texts.js';

const SITE_OF = {
  'guide-kameduli': 'kameduly',
  'guide-las-bielanski': 'las-bielanski',
  'guide-awf': 'awf',
  'guide-uksw-dewajtis': 'uksw',
  'guide-metro-stare-bielany': 'stare-bielany',
  'guide-metro-wawrzyszew': 'wawrzyszew',
  'guide-metro-mlociny': 'mlociny',
  'guide-szpital-bielanski': 'szpital-bielanski',
  'guide-mlociny': 'galeria-mlociny',
  'guide-sw-zygmunt': 'sw-zygmunt',
  'guide-sw-maria-magdalena': 'maria-magdalena',
};

const md = fs.readFileSync(ROOT + 'docs/teksty-przewodnika.md', 'utf8');
const block = md.match(/```json\n([\s\S]*?)\n```/);
if (!block) throw new Error('no JSON block in docs/teksty-przewodnika.md');
const texts = JSON.parse(block[1]).flatMap((t) => {
  if (t.kind === 'guide') {
    if (!SITE_OF[t.id]) throw new Error(`guide text ${t.id} has no site in tools/guide-texts.mjs`);
    return [{ id: t.id, kind: 'guide', landmark: SITE_OF[t.id], sms: t.sms, more: t.more || '', sources: t.sources || [] }];
  }
  if (PUBLIC) return [];
  return [{ id: t.id, kind: 'mayor', trigger: t.id === 'mayor-welcome' ? 'start' : 'delivery', sms: t.sms, sources: t.sources || [] }];
});

fs.writeFileSync(OUT, `// js/guide-texts.js — GENERATED by tools/guide-texts.mjs from docs/teksty-przewodnika.md, do not edit by hand.
// The guide's messages at the landmarks${PUBLIC ? '' : " and the mayor's draft messages (localhost only, see js/guide.js)"}.
export const GUIDE_TEXTS = ${JSON.stringify(texts, null, 1)};
`);
console.log(`[guide-texts] ${texts.filter((t) => t.kind === 'guide').length} guide, ${texts.filter((t) => t.kind === 'mayor').length} mayor texts -> ${OUT}`);
