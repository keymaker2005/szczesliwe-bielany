// tools/wiedza-burmistrza.mjs
// Builds the "Burmistrz Bielan" chat knowledge for the Worker: worker/src/wiedza-burmistrza.js exports MAYOR_SYSTEM, one
// string made of the character's instructions (worker/prompts/burmistrz.md), the district knowledge from public pages
// (docs/wiedza-burmistrza.md) and the guide's base (docs/wiedza-przewodnika.md: landmarks, estates, metro, nature).
//
// usage: node tools/wiedza-burmistrza.mjs     write worker/src/wiedza-burmistrza.js, print the token estimate

import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const DOC = ROOT + 'docs/wiedza-burmistrza.md';
const GUIDE_DOC = ROOT + 'docs/wiedza-przewodnika.md';
const PROMPT = ROOT + 'worker/prompts/burmistrz.md';
const OUT = ROOT + 'worker/src/wiedza-burmistrza.js';
const TOKEN_GOAL = 20000;

// The sections of a knowledge doc: everything from its first "## " heading on, without comments
const body = (md) => md.slice(md.indexOf('\n## ') + 1).replace(/<!--[\s\S]*?-->\n?/g, '').trim();

export function build(md = fs.readFileSync(DOC, 'utf8'), guideMd = fs.readFileSync(GUIDE_DOC, 'utf8'), prompt = fs.readFileSync(PROMPT, 'utf8')) {
  return `${prompt.trim()}\n\n# BAZA WIEDZY\n\n${body(md)}\n\n${body(guideMd)}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const system = build();
  fs.writeFileSync(OUT, `// worker/src/wiedza-burmistrza.js — GENERATED by tools/wiedza-burmistrza.mjs from worker/prompts/burmistrz.md,
// docs/wiedza-burmistrza.md and docs/wiedza-przewodnika.md, do not edit by hand. The mayor character's fixed system prompt.
export const MAYOR_SYSTEM = ${JSON.stringify(system)};
`);
  const tokens = Math.round(system.length / 4);
  console.log(`[wiedza-burmistrza] ${system.length} znaków, ok. ${tokens} tokenów (cel do ${TOKEN_GOAL}) -> ${OUT}`);
  if (tokens > TOKEN_GOAL) console.warn('UWAGA: powyżej celu tokenów');
}
