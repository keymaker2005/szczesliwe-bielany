// tools/wiedza-przewodnika.mjs
// Builds the guide's chat knowledge for the Worker: worker/src/wiedza-przewodnika.js exports GUIDE_SYSTEM, one string
// made of the instructions (worker/prompts/przewodnik.md) and the knowledge base (docs/wiedza-przewodnika.md).
// The landmark section of the base sits between markers and is generated from js/guide-texts.js and js/guide.js, so the
// chat and the phone's Przewodnik app say the same.
//
// usage: node tools/wiedza-przewodnika.mjs          write worker/src/wiedza-przewodnika.js, print the token estimate
//        node tools/wiedza-przewodnika.mjs --docs   also refresh the landmark section in docs/wiedza-przewodnika.md

import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { NAMES, SITES } from '../js/guide.js';
import { GUIDE_TEXTS } from '../js/guide-texts.js';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const DOC = ROOT + 'docs/wiedza-przewodnika.md';
const PROMPT = ROOT + 'worker/prompts/przewodnik.md';
const OUT = ROOT + 'worker/src/wiedza-przewodnika.js';
const START = '<!-- LANDMARKI:START (generowane przez tools/wiedza-przewodnika.mjs --docs z js/guide-texts.js) -->';
const END = '<!-- LANDMARKI:END -->';
const TOKEN_GOAL = 15000;

export function landmarkSection() {
  return GUIDE_TEXTS.filter((t) => t.kind === 'guide' && SITES[t.landmark]).map((t) =>
    `### ${NAMES[t.landmark] || t.landmark} [id: ${t.landmark}]\n${t.sms}\n\n${t.more}\n\nŹródła: ${t.sources.join(' ')}\n`,
  ).join('\n');
}

export function refreshDocs(md) {
  const a = md.indexOf(START);
  const b = md.indexOf(END);
  if (a < 0 || b < a) throw new Error('markers LANDMARKI:START/END missing in docs/wiedza-przewodnika.md');
  return `${md.slice(0, a + START.length)}\n\n${landmarkSection()}\n${md.slice(b)}`;
}

export function build(md = fs.readFileSync(DOC, 'utf8'), prompt = fs.readFileSync(PROMPT, 'utf8')) {
  const base = md.slice(md.indexOf('\n## ') + 1).replace(/<!--[\s\S]*?-->\n?/g, '').trim();
  return `${prompt.trim()}\n\n# BAZA WIEDZY\n\n${base}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let md = fs.readFileSync(DOC, 'utf8');
  if (process.argv.includes('--docs')) {
    md = refreshDocs(md);
    fs.writeFileSync(DOC, md);
  }
  const system = build(md);
  fs.writeFileSync(OUT, `// worker/src/wiedza-przewodnika.js — GENERATED by tools/wiedza-przewodnika.mjs from worker/prompts/przewodnik.md and
// docs/wiedza-przewodnika.md, do not edit by hand. The guide's fixed system prompt (instructions + knowledge base).
export const GUIDE_SYSTEM = ${JSON.stringify(system)};
`);
  const tokens = Math.round(system.length / 4);
  console.log(`[wiedza-przewodnika] ${system.length} znaków, ok. ${tokens} tokenów (cel do ${TOKEN_GOAL}) -> ${OUT}`);
  if (tokens > TOKEN_GOAL) console.warn('UWAGA: powyżej celu tokenów');
}
